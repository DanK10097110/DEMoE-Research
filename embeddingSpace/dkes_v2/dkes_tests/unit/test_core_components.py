class TestKDMWriteCapacity:
    """Verify write behavior and capacity management."""

    def test_write_and_count(self):
        rng = make_rng(5)
        kdm = MockKDM(dim=64, capacity=50)
        vecs = unit_sphere(rng, 20, 64)
        for i, v in enumerate(vecs):
            kdm.write(f"c_{i}", v, v)
        assert kdm.slot_count() == 20

    def test_write_overwrites_oldest_at_capacity(self):
        rng = make_rng(6)
        kdm = MockKDM(dim=64, capacity=5)
        vecs = unit_sphere(rng, 10, 64)
        for i, v in enumerate(vecs):
            kdm.write(f"c_{i}", v, v)
        # After 10 writes into capacity=5, only 5 should remain
        assert kdm.slot_count() == 5

    def test_distinct_concepts_have_distinct_reads(self):
        """Two very different queries should read from different value regions."""
        rng = make_rng(7)
        kdm = MockKDM(dim=128, capacity=20)
        # Two opposite clusters
        c1 = unit_sphere(rng, 1, 128)[0]
        c2 = -c1  # antipodal
        v1 = unit_sphere(rng, 1, 128)[0]
        v2 = unit_sphere(rng, 1, 128)[0]
        kdm.write("cluster_a", c1, v1)
        kdm.write("cluster_b", c2, v2)

        r1 = kdm.read(c1, beta=20.0)
        r2 = kdm.read(c2, beta=20.0)
        cos_cross = float(np.dot(r1, r2))
        assert cos_cross < 0.5, (
            f"Reads for antipodal queries should differ; cross-cosine={cos_cross:.4f}"
        )


