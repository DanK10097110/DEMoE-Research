# 5. Routing Logic (MRL Funnel Mathematics)
# ─────────────────────────────────────────────────────────────────────────────

class TestRoutingMath:
    """Test the two-stage MRL funnel's selection and deduplication logic."""

    def test_coarse_stage_reduces_candidates(self):
        """Stage 1 (64-dim prefix) should reduce from full corpus to k_coarse."""
        rng = make_rng(30)
        corpus_size = 500
        coarse_dim  = 64
        k_coarse    = 20

        corpus_coarse = unit_sphere(rng, corpus_size, coarse_dim)
        query_coarse  = unit_sphere(rng, 1, coarse_dim)[0]

        # Stage 1: cosine search in coarse space
        sims   = corpus_coarse @ query_coarse
        idx    = np.argsort(-sims)[:k_coarse]
        assert len(idx) == k_coarse

    def test_fine_stage_reranks_within_candidates(self):
        """Stage 2 (768-dim) should produce different ordering than stage 1."""
        rng = make_rng(31)
        k_coarse = 20
        fine_dim = 128

        # Build candidates that look similar at 64-dim but differ at 128-dim
        candidates_fine = unit_sphere(rng, k_coarse, fine_dim)
        query_fine      = unit_sphere(rng, 1, fine_dim)[0]

        # Stage 1 order (random for this test — we just need something)
        stage1_order = list(range(k_coarse))

        # Stage 2 rerank
        sims_fine   = candidates_fine @ query_fine
        stage2_idx  = np.argsort(-sims_fine)

        # The reranked order should exist and be a permutation
        assert sorted(stage2_idx) == list(range(k_coarse))
        # Very likely to differ from stage1_order
        assert not np.array_equal(stage2_idx, stage1_order) or k_coarse <= 2

    def test_concept_overlap_merge(self):
        """Candidates with cosine similarity > threshold should be merged."""
        rng = make_rng(32)
        dim = 128
        threshold = 0.80

        base = unit_sphere(rng, 1, dim)[0]
        # Two near-duplicates
        dup1 = base + rng.standard_normal(dim).astype(np.float32) * 0.02
        dup1 /= np.linalg.norm(dup1)
        dup2 = base + rng.standard_normal(dim).astype(np.float32) * 0.02
        dup2 /= np.linalg.norm(dup2)
        # One distinct
        distinct = unit_sphere(rng, 1, dim)[0]

        candidates = [base, dup1, dup2, distinct]
        ids = ["a", "b", "c", "d"]

        merged = []
        seen_vecs = []
        for cid, emb in zip(ids, candidates):
            is_dup = any(float(np.dot(emb, s)) > threshold for s in seen_vecs)
            if not is_dup:
                merged.append(cid)
                seen_vecs.append(emb)

        assert "a" in merged
        assert "d" in merged
        assert len(merged) <= 2, f"Expected ≤2 after dedup, got {len(merged)}"

    def test_budget_cap(self):
        """Final selection must not exceed M_active = 3 experts."""
        M_active = 3
        candidates = ["e1", "e2", "e3", "e4", "e5"]
        selected = candidates[:M_active]
        assert len(selected) <= M_active

    def test_deadlock_fallback(self):
        """If all candidates fall below routing threshold, fallback should fire."""
        threshold = 0.60
        scores = [0.30, 0.25, 0.20]  # all below threshold
        deadlock = all(s < threshold for s in scores)
        assert deadlock, "Should detect deadlock when all scores below threshold"
        # Fallback: take top-1 regardless
        fallback = [scores.index(max(scores))]
        assert len(fallback) == 1


