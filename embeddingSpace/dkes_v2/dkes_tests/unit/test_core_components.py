# 4. ColdStore Logic
# ─────────────────────────────────────────────────────────────────────────────

class TestColdStoreLogic:
    """
    Verify archive → search → reactivate cycle.

    Based on Section 1.A mitigation: evicted concepts must be findable
    and re-writable into live slots if a similar query re-appears.
    """

    def _make_cold_store_archive(self) -> Tuple:
        """Helper: simulate archiving 20 concept centroids."""
        rng = make_rng(20)
        dim = 128
        centroids = unit_sphere(rng, 20, dim)
        archive   = {}  # concept_id → (address, value)
        for i, c in enumerate(centroids):
            cid = f"evicted_{i}"
            archive[cid] = (c.copy(), c.copy())  # address == value for simplicity
        return archive, centroids, dim, rng

    def test_similar_query_finds_archived_concept(self):
        archive, centroids, dim, rng = self._make_cold_store_archive()

        # Query close to concept 5
        noise = rng.standard_normal(dim).astype(np.float32) * 0.05
        query = centroids[5] + noise
        query /= np.linalg.norm(query)

        # Brute-force cosine search over archive
        best_cid = None
        best_cos = -1.0
        for cid, (addr, _) in archive.items():
            cos = float(np.dot(query, addr))
            if cos > best_cos:
                best_cos = cos
                best_cid = cid

        assert best_cid == "evicted_5", (
            f"Expected to find evicted_5, found {best_cid} (cos={best_cos:.4f})"
        )
        assert best_cos > 0.90, f"Reactivation candidate similarity too low: {best_cos:.4f}"

    def test_reactivation_removes_from_archive(self):
        archive, centroids, dim, _ = self._make_cold_store_archive()
        initial_count = len(archive)
        del archive["evicted_5"]
        assert len(archive) == initial_count - 1

    def test_dissimilar_query_does_not_trigger_reactivation(self):
        archive, centroids, dim, rng = self._make_cold_store_archive()
        # Random query, not close to any archived concept
        random_q = unit_sphere(rng, 1, dim)[0]
        best_cos = max(
            float(np.dot(random_q, addr))
            for addr, _ in archive.values()
        )
        # Reactivation threshold is typically 0.85 — random should be below 0.5
        REACTIVATION_THRESHOLD = 0.85
        if best_cos >= REACTIVATION_THRESHOLD:
            pytest.skip("Random query happened to be close to archive — harmless fluke")
        assert best_cos < REACTIVATION_THRESHOLD


