# 3. Composite Embedding Quality
# ─────────────────────────────────────────────────────────────────────────────

class TestCompositeEmbedding:
    """
    Verify composite q̃ = LN(e + γ·r) improves semantic alignment.

    Methodology: create a query whose backbone embedding is ambiguous
    (equidistant between two concept clusters), populate KDM with both
    clusters, then verify the composite resolves the ambiguity.
    """

    def test_memory_biases_composite_toward_seen_concept(self):
        """
        Composite should be closer to a seen concept than backbone alone.
        """
        rng = make_rng(10)
        dim = 128
        kdm = MockKDM(dim=dim, capacity=50)

        # Two concept clusters
        c_a = unit_sphere(rng, 1, dim)[0]
        c_b = unit_sphere(rng, 1, dim)[0]
        v_a = unit_sphere(rng, 1, dim)[0]
        v_b = unit_sphere(rng, 1, dim)[0]
        kdm.write("concept_a", c_a, v_a)
        kdm.write("concept_b", c_b, v_b)

        # Query close to concept_a
        noise = rng.standard_normal(dim).astype(np.float32) * 0.10
        q = c_a + noise
        q /= np.linalg.norm(q)

        # Backbone similarity to concepts
        cos_a_backbone = float(np.dot(q, c_a))
        cos_b_backbone = float(np.dot(q, c_b))

        # Memory read
        r = kdm.read(q, beta=15.0)
        gamma = 0.3

        composite = q + gamma * r
        composite /= np.linalg.norm(composite)

        cos_a_comp = float(np.dot(composite, c_a))
        cos_b_comp = float(np.dot(composite, c_b))

        # Composite should be closer to a than backbone was
        delta = (cos_a_comp - cos_a_backbone)
        assert delta >= -0.02, (
            f"Composite should not degrade similarity to seen concept; delta={delta:.4f}"
        )

    def test_gamma_zero_equals_backbone(self):
        """When γ=0, composite must equal backbone embedding."""
        rng = make_rng(11)
        dim = 64
        e = unit_sphere(rng, 1, dim)[0]
        r = unit_sphere(rng, 1, dim)[0]
        gamma = 0.0
        composite = e + gamma * r
        assert np.allclose(composite, e), "γ=0 composite must equal backbone"

    def test_layer_norm_unit_norm(self):
        """LayerNorm output (re-normalized) should remain unit norm."""
        rng = make_rng(12)
        dim = 768
        e = unit_sphere(rng, 1, dim)[0]
        r = unit_sphere(rng, 1, dim)[0]
        gamma = 0.4
        composite = e + gamma * r
        # Apply LN-style normalization: zero-mean, unit-std
        composite = (composite - composite.mean()) / (composite.std() + 1e-8)
        # Re-normalize to unit sphere for cosine similarity use
        composite /= np.linalg.norm(composite)
        assert abs(np.linalg.norm(composite) - 1.0) < 1e-5


