# 1. KDM Memory Mathematics
# ─────────────────────────────────────────────────────────────────────────────

class TestKDMReadMath:
    """Verify the Kanerva attention-weighted read formula is correct."""

    def test_exact_address_returns_correct_value(self):
        """When query == slot address, that slot should dominate the read."""
        rng = make_rng(0)
        kdm = MockKDM(dim=64, capacity=10)

        addresses = unit_sphere(rng, 5, 64)
        values    = unit_sphere(rng, 5, 64)
        for i, (a, v) in enumerate(zip(addresses, values)):
            kdm.write(f"c_{i}", a, v)

        # Query exactly matching slot 2
        result = kdm.read(addresses[2], beta=50.0)
        cos_to_target = float(np.dot(result, values[2]))
        assert cos_to_target > 0.90, (
            f"Read result should be close to target value, got cos={cos_to_target:.4f}"
        )

    def test_empty_memory_returns_zero(self):
        """Empty KDM should return zero vector."""
        kdm = MockKDM(dim=128)
        query = unit_sphere(make_rng(1), 1, 128)[0]
        result = kdm.read(query)
        assert np.allclose(result, 0), "Empty KDM must return zero vector"

    def test_attention_weights_sum_to_one(self):
        """Softmax attention weights over slots must sum to 1."""
        rng = make_rng(2)
        dim = 64

        addresses = unit_sphere(rng, 10, dim)
        query     = unit_sphere(rng, 1, dim)[0]

        cosines = addresses @ query
        beta = 10.0
        exp_scores = np.exp(beta * (cosines - cosines.max()))
        weights = exp_scores / exp_scores.sum()

        assert abs(weights.sum() - 1.0) < 1e-5, "Attention weights must sum to 1"

    def test_high_beta_sharpens_attention(self):
        """Higher beta should make attention more peaked."""
        rng = make_rng(3)
        dim = 64
        addresses = unit_sphere(rng, 20, dim)
        query = addresses[0]  # exact match to slot 0

        def max_weight(beta):
            cosines = addresses @ query
            exp_scores = np.exp(beta * (cosines - cosines.max()))
            weights = exp_scores / exp_scores.sum()
            return weights.max()

        w_low  = max_weight(beta=1.0)
        w_high = max_weight(beta=50.0)
        assert w_high > w_low, "Higher beta should produce sharper (more peaked) attention"
        assert w_high > 0.90, f"Very high beta should nearly one-hot; got {w_high:.4f}"

    def test_gamma_interpolation(self):
        """Composite = LayerNorm(e + γ·r) — verify the math, not the LN."""
        rng = make_rng(4)
        dim = 768
        e = unit_sphere(rng, 1, dim)[0]  # backbone embedding
        r = unit_sphere(rng, 1, dim)[0]  # memory read result
        gamma = 0.3

        composite_unnorm = e + gamma * r
        # Check dimensionality and dtype
        assert composite_unnorm.shape == (dim,)
        assert composite_unnorm.dtype == np.float32


