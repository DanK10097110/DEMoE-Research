class TestSerializationRoundtrip:
    """Verify checkpoint save/load preserves numerical precision."""

    def test_numpy_b64_roundtrip(self):
        """Base64-encoded numpy arrays should decode with no precision loss."""
        import base64
        rng = make_rng(40)
        arr = rng.standard_normal((256, 768)).astype(np.float32)

        # Encode
        b64 = base64.b64encode(arr.tobytes()).decode("ascii")
        meta = {"dtype": str(arr.dtype), "shape": list(arr.shape)}

        # Decode
        raw   = base64.b64decode(b64.encode("ascii"))
        arr2  = np.frombuffer(raw, dtype=meta["dtype"]).reshape(meta["shape"])

        assert np.array_equal(arr, arr2), "Float32 arrays must round-trip exactly via base64"

    def test_config_json_roundtrip(self):
        """DKESConfig should serialize and deserialize without mutation."""
        import json
        import sys
        sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
        try:
            from dkes.utils.config import DKESConfig
            cfg = DKESConfig()
            cfg.kdm.total_slots = 1024
            d1 = cfg.to_dict()
            serialized = json.dumps(d1)
            d2 = json.loads(serialized)
            assert d1 == d2, "Config dict must survive JSON round-trip unchanged"
        except ImportError:
            pytest.skip("DKES package not installed; skipping config roundtrip")


