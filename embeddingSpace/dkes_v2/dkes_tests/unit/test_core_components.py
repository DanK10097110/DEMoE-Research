# 7. Thread Safety
# ─────────────────────────────────────────────────────────────────────────────

class TestThreadSafety:
    """
    Verify concurrent reads and writes don't corrupt memory state.
    This is critical given DKES is designed for multi-expert concurrent use.
    """

    def test_concurrent_reads_do_not_crash(self):
        rng = make_rng(50)
        kdm = MockKDM(dim=64, capacity=100)
        vecs = unit_sphere(rng, 20, 64)
        for i, v in enumerate(vecs):
            kdm.write(f"c_{i}", v, v)

        errors = []
        results = []
        lock = threading.Lock()

        def reader(q):
            try:
                r = kdm.read(q, beta=10.0)
                with lock:
                    results.append(r)
            except Exception as e:
                with lock:
                    errors.append(e)

        queries = unit_sphere(rng, 50, 64)
        threads = [threading.Thread(target=reader, args=(q,)) for q in queries]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=5.0)

        assert not errors, f"Thread errors: {errors}"
        assert len(results) == 50

    def test_write_read_concurrency_no_deadlock(self):
        """Mixed reads and writes should complete without deadlock."""
        rng = make_rng(51)
        kdm = MockKDM(dim=64, capacity=200)
        done = []
        errors = []
        lock = threading.Lock()

        def worker(i):
            try:
                v = unit_sphere(rng, 1, 64)[0]
                kdm.write(f"c_{i}", v, v)
                kdm.read(v, beta=10.0)
                with lock:
                    done.append(i)
            except Exception as e:
                with lock:
                    errors.append(e)

        threads = [threading.Thread(target=worker, args=(i,)) for i in range(30)]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=10.0)

        assert not errors, f"Errors: {errors}"
        assert len(done) == 30, f"Only {len(done)}/30 workers completed"


